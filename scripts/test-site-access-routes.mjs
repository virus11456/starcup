import { registerHooks } from 'node:module';
import { resolve as pathResolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
registerHooks({resolve(specifier,context,next){
  if(specifier==='next/server') specifier='next/server.js';
  if(specifier.startsWith('@/'))specifier=pathToFileURL(pathResolve(specifier.slice(2)+'.ts')).href;
  if(specifier==='./lib/site-access')specifier='./lib/site-access.ts';
  return next(specifier,context);
}});
process.env.SITE_ACCESS_PASSWORD='route-test-only';
process.env.SITE_ACCESS_SESSION_SECRET='11'.repeat(32);
const {NextRequest}=await import('next/server.js');
const {proxy}=await import('../proxy.ts');
const {POST}=await import('../app/api/access/route.ts');
const req=(path,options={})=>new NextRequest('https://site.test'+path,options);
for(const path of ['/','/full','/engine/index.html','/engine/grail.css','/qa-layout.html','/_next/image','/full-engine/catalog.json'])assert.equal(proxy(req(path)).status,307,path);
assert.equal(proxy(req('/api/game')).status,401);
const post=(body,headers={})=>POST(req('/api/access',{method:'POST',body:new URLSearchParams(body),headers:{Origin:'https://site.test','Content-Type':'application/x-www-form-urlencoded',...headers}}));
assert.equal((await post({password:'wrong'})).headers.has('set-cookie'),false);
assert.equal((await post({password:'route-test-only'},{Origin:'https://evil.test'})).status,403);
const good=await post({password:'route-test-only',next:'/full'});
assert.equal(good.status,303);assert.equal(good.headers.get('location'),'https://site.test/full');
const cookie=good.headers.get('set-cookie').split(';')[0];
assert.match(good.headers.get('set-cookie'),/HttpOnly/);
assert.equal(proxy(req('/full',{headers:{Cookie:cookie}})).status,200);
assert.equal(proxy(req('/api/game',{headers:{Cookie:cookie}})).status,200);
assert.equal(proxy(req('/full',{headers:{Cookie:cookie.slice(0,-1)+'x'}})).status,307);
assert.equal((await post({action:'lock'},{Cookie:cookie})).cookies.get('grail_access').value,'');
const {GET:gameGet,POST:gamePost}=await import('../app/api/game/route.ts');
assert.equal((await gameGet(req('/api/game'))).status,401);
assert.equal((await gamePost(req('/api/game',{method:'POST'}))).status,401);
const tooLarge=await post({password:'x'.repeat(5000)});assert.equal(tooLarge.status,413);
for(let i=0;i<10;i++)await post({password:'wrong'});
const limited=await post({password:'route-test-only'});assert.match(limited.headers.get('location'),/error=rate/);
delete process.env.SITE_ACCESS_PASSWORD;
assert.equal((await post({password:'route-test-only'})).status,503);
assert.equal(proxy(req('/full',{headers:{Cookie:cookie}})).status,307);
console.log('Route, API defense, body limit, throttling and fail-closed checks passed');
