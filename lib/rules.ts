function normalize(s: string) {
  const pairs: Record<string, string> = {
    应: "應",
    战: "戰",
    气: "氣",
    击: "擊",
    张: "張",
    圣: "聖",
    传: "傳",
    递: "遞",
    买: "買",
    炼: "煉",
    虚: "虛",
    场: "場",
    弃: "棄",
    伤: "傷",
    库: "庫",
    弹: "彈",
    则: "則",
    输: "輸",
    赢: "贏",
    队: "隊",
    连: "連",
    线: "線",
    术: "術",
  };
  return s
    .normalize("NFKC")
    .toLowerCase()
    .replace(
      /[应战气击张圣传递买炼虚场弃伤库弹则输赢队连线术]/g,
      (c) => pairs[c],
    )
    .replace(/[\s，。？?！!、]/g, "");
}
export function searchRules(query: string, category = "全部") {
  const q = normalize(query);
  const candidates = RULES.filter(
    (r) => category === "全部" || r.category === category,
  );
  if (!q) return candidates;
  return candidates
    .map((rule) => {
      const title = normalize(rule.title);
      let score = rule.keywords.reduce(
        (n, k) => n + (q.includes(normalize(k)) ? k.length * 4 : 0),
        0,
      );
      if (title.includes(q)) score += 30;
      for (let i = 0; i < q.length - 1; i++) {
        const gram = q.slice(i, i + 2);
        if (title.includes(gram)) score += 2;
      }
      return { rule, score };
    })
    .filter((r) => r.score >= 4)
    .sort((a, b) => b.score - a.score)
    .map((r) => r.rule);
}
